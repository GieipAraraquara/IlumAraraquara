-- 1. Garante a coluna ID como Primary Key gerada por default
DO $$ 
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'localizacao_pracas' 
          AND column_name = 'id'
    ) THEN
        ALTER TABLE public.localizacao_pracas ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
    END IF;
END $$;

-- 2. Habilita RLS caso ainda não esteja
ALTER TABLE public.localizacao_pracas ENABLE ROW LEVEL SECURITY;

-- 3. Políticas de Acesso
DROP POLICY IF EXISTS "Permitir leitura publica localizacao_pracas" ON public.localizacao_pracas;
CREATE POLICY "Permitir leitura publica localizacao_pracas"
    ON public.localizacao_pracas FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Permitir inserção de praças" ON public.localizacao_pracas;
CREATE POLICY "Permitir inserção de praças"
    ON public.localizacao_pracas FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir atualização de praças" ON public.localizacao_pracas;
CREATE POLICY "Permitir atualização de praças"
    ON public.localizacao_pracas FOR UPDATE
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir exclusão de praças" ON public.localizacao_pracas;
CREATE POLICY "Permitir exclusão de praças"
    ON public.localizacao_pracas FOR DELETE
    USING (true);

-- 4. Garantir permissões de acesso aos papéis do Supabase
GRANT ALL ON TABLE public.localizacao_pracas TO anon;
GRANT ALL ON TABLE public.localizacao_pracas TO authenticated;
GRANT ALL ON TABLE public.localizacao_pracas TO service_role;

-- 5. Atualizar automaticamente a coluna espacial quando lat/lng mudarem
CREATE OR REPLACE FUNCTION public.fn_atualizar_espacial_praca()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW."Latitude" IS NOT NULL AND NEW."Longitude" IS NOT NULL THEN
        NEW."localizacao_espacial" := ST_SetSRID(ST_MakePoint(NEW."Longitude", NEW."Latitude"), 4326)::geography;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_atualizar_espacial_praca ON public.localizacao_pracas;
CREATE TRIGGER trg_atualizar_espacial_praca
BEFORE INSERT OR UPDATE OF "Latitude", "Longitude" ON public.localizacao_pracas
FOR EACH ROW
EXECUTE FUNCTION public.fn_atualizar_espacial_praca();

-- 6. Recarregar o cache do PostgREST
NOTIFY pgrst, 'reload schema';
